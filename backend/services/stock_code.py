# ===================================================
# 銘柄コードの判定・変換
#
# 日本株の銘柄コードは「4文字」（J-Quants・ウォッチリストでは末尾に 0 を付けた5文字）。
# 2024年1月から東証は、新しく上場する銘柄に英字入りのコードを使っている
# （例：285A キオクシア、130A）。1・3文字目は数字、2・4文字目は数字か英大文字。
#
# 以前は code.isdigit() で日本株かどうかを判定していたため、英字入りのコードは
# 米国株として扱われ、株価・詳細・AI分析・決算日が取れなかった。
# 日本株かどうかの判定と yfinance 用への変換は、必ずこのモジュールを使うこと。
#
#   J-Quants / ウォッチリスト : 72030 / 285A0   （5文字）
#   画面表示                  : 7203  / 285A    （4文字）
#   yfinance                  : 7203.T / 285A.T
# ===================================================

import re

# 4文字（画面表示）か、末尾に1文字付いた5文字（J-Quants）。
# 米国株のティッカーは数字で始まらないので、1文字目が数字かどうかで区別できる
_JP_CODE = re.compile(r"^[0-9][0-9A-Z][0-9][0-9A-Z][0-9]?$")


def is_jp_code(code: str) -> bool:
    """日本株の銘柄コード（4文字または5文字。英字入りも含む）なら True"""
    return bool(_JP_CODE.match(code or ""))


def to_yf_ticker(code: str) -> str:
    """yfinance 用のティッカーにする（日本株は4文字＋".T"、それ以外はそのまま）"""
    return f"{code[:4]}.T" if is_jp_code(code) else code


def to_jquants_code(code: str) -> str:
    """J-Quants 用の5文字コードにする（例：7203 → 72030、285A → 285A0）"""
    return code[:4] + "0"
