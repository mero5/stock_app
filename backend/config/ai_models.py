# スイング分析・ポートフォリオ診断・市況コメント
OPENAI_ANALYSIS_MODEL = "gpt-5-mini"

# ニュース翻訳・AI相談（軽い処理なので、いちばん安いモデル）
OPENAI_LIGHT_MODEL = "gpt-4o-mini"

# GPT-5系（考えてから答えるモデル）が考える量。
# 上げるほど賢くなるが、遅く・高くなる。
# OPENAI_TIMEOUT_SEC（90秒）に収まるよう low にしている
OPENAI_REASONING_EFFORT = "low"

# GPT-5系は「考えた分（思考トークン）」も出力の上限に数えられる。
# 回答に必要な分だけを上限にすると、考えるだけで使い切って答えが空になるので、
# 回答の上限にこの分を足す。料金は実際に使った分だけなので、上限を上げても高くはならない
OPENAI_REASONING_TOKEN_BUDGET = 8000
