# ===================================================
# 外部APIのタイムアウト設定
#
# タイムアウトを指定しないと、相手が応答しないときに
# 永遠に待ち続ける（requests は既定でタイムアウト無し、
# OpenAI SDK は既定で 600秒 x 最大2回リトライ）。
# Lambda は最大15分で強制終了されるため、
# 「15分制限でエラー」の原因になっていた可能性が高い。
#
# アプリ側は AI系APIを120秒で打ち切る（StockService.aiTimeout）ので、
# それより短い値にしている。
# ===================================================

# J-Quants（requests）: (接続タイムアウト秒, 読み込みタイムアウト秒)
# 銘柄マスタは全上場銘柄ぶんでレスポンスが大きいので読み込みは長めにする
JQUANTS_TIMEOUT = (5, 30)

# OpenAI: 1回の呼び出しの上限秒数とリトライ回数
# リトライすると合計がアプリ側の120秒を超えて無駄になるので0にする
OPENAI_TIMEOUT_SEC = 90
OPENAI_MAX_RETRIES = 0

# Gemini: 1回の呼び出しの上限秒数
GEMINI_TIMEOUT_SEC = 60
