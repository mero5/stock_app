def get_notices(since: int = 0) -> list:
    """
    告知を version の小さい順に返す。

    [since] この値より大きい version の告知だけを返す（未読分の取得用）。
            0を渡すと全件返る（お知らせ履歴の表示用）。
    """
    try:
        since = int(since or 0)
    except (TypeError, ValueError):
        since = 0
    return [n for n in NOTICES if int(n["version"]) > since]


def latest_version() -> int:
    """最新の告知バージョン。告知が1件も無ければ0"""
    return max((int(n["version"]) for n in NOTICES), default=0)
