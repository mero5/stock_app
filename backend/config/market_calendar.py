# ===================================================
# FOMC・日銀 金融政策決定会合の日程（固定データ）
#
# ★年1回の更新が必要★
#   ・FOMC：米FRBが前年の夏ごろに翌年の日程を公表
#     https://www.federalreserve.gov/monetarypolicy/fomccalendars.htm
#   ・日銀：例年7月末ごろに翌年の日程を公表
#     https://www.boj.or.jp/mopo/mpmsche_minu/index.htm
#   公表されたら、下のリストに1年分（各8回）を足して deploy する。
#   足し忘れると、スケジュール画面と「直近の予定」に表示されなくなる。
#
# 日付の決め方：
#   ・FOMC は2日間の会合の「2日目」（結果発表日。米国時間）
#   ・日銀 は2日間の会合の「2日目」（結果発表日）
#
# 以前は routers/market.py の関数の中に直書きしていたが、
# 更新漏れに気づけるよう、ここに切り出して確認用の関数を付けた。
# ===================================================

FOMC_DATES = [
    # 2025
    "2025-01-29", "2025-03-19", "2025-05-07", "2025-06-18",
    "2025-07-30", "2025-09-17", "2025-10-29", "2025-12-10",
    # 2026
    "2026-01-28", "2026-03-18", "2026-04-29", "2026-06-17",
    "2026-07-29", "2026-09-16", "2026-10-28", "2026-12-09",
    # 2027（FRB公表。各会合の直前の会合で確定するまでは暫定扱い）
    "2027-01-27", "2027-03-17", "2027-04-28", "2027-06-09",
    "2027-07-28", "2027-09-15", "2027-10-27", "2027-12-08",
]

BOJ_DATES = [
    # 2025
    "2025-01-24", "2025-03-19", "2025-05-01", "2025-06-17",
    "2025-07-31", "2025-09-19", "2025-10-29", "2025-12-19",
    # 2026
    "2026-01-23", "2026-03-19", "2026-04-28", "2026-06-16",
    "2026-07-30", "2026-09-17", "2026-10-28", "2026-12-18",
    # 2027（日銀 2026-07-31 公表）
    "2027-01-22", "2027-03-18", "2027-04-28", "2027-06-11",
    "2027-07-22", "2027-09-22", "2027-10-29", "2027-12-17",
]


def last_registered_year() -> int:
    """FOMC・日銀の両方の日程が登録されている最後の年"""
    fomc_last = max(int(d[:4]) for d in FOMC_DATES)
    boj_last  = max(int(d[:4]) for d in BOJ_DATES)
    return min(fomc_last, boj_last)


def warn_if_missing(year: int) -> None:
    """日程が未登録の年を問い合わせられたらログに警告を出す（更新漏れに気づくため）"""
    if year > last_registered_year():
        print(f"警告: {year}年のFOMC・日銀の日程が未登録です（config/market_calendar.py を更新してください）")
